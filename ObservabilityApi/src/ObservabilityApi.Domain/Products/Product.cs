using System.Text.RegularExpressions;

namespace ObservabilityApi.Domain.Products;

/// <summary>
/// Product aggregate. Owns its invariants; persistence concerns (keys, concurrency tokens)
/// are mapped by Infrastructure and never interpreted here.
/// </summary>
public sealed partial class Product
{
    public const int SkuMinLength = 2;
    public const int SkuMaxLength = 32;
    public const int NameMaxLength = 200;
    public const int DescriptionMaxLength = 2000;
    public const decimal MaxPrice = 1_000_000m;
    public const int PriceDecimalPlaces = 2;

    // Required by EF Core for materialization.
    private Product()
    {
    }

    public Guid Id { get; private set; }

    /// <summary>Stock keeping unit. Normalized to upper case and immutable after creation.</summary>
    public string Sku { get; private set; } = null!;

    public string Name { get; private set; } = null!;

    public string? Description { get; private set; }

    public decimal Price { get; private set; }

    public DateTimeOffset CreatedAtUtc { get; private set; }

    public DateTimeOffset UpdatedAtUtc { get; private set; }

    /// <summary>Optimistic concurrency token, generated by the database.</summary>
    public byte[] RowVersion { get; private set; } = [];

    public static Product Create(string sku, string name, string? description, decimal price, DateTimeOffset nowUtc)
    {
        var normalizedSku = NormalizeSku(sku);
        if (!IsValidSku(normalizedSku))
        {
            throw new DomainException(
                $"SKU must be {SkuMinLength}-{SkuMaxLength} characters: letters, digits and '-', starting with a letter or digit.");
        }

        var product = new Product
        {
            Sku = normalizedSku,
            CreatedAtUtc = nowUtc,
        };
        product.SetDetails(name, description, price, nowUtc);
        return product;
    }

    public void Update(string name, string? description, decimal price, DateTimeOffset nowUtc)
        => SetDetails(name, description, price, nowUtc);

    public static string NormalizeSku(string? sku) => (sku ?? string.Empty).Trim().ToUpperInvariant();

    /// <summary>Validates an already-normalized SKU. Shared with request validators so the rule lives in one place.</summary>
    public static bool IsValidSku(string normalizedSku)
        => normalizedSku.Length is >= SkuMinLength and <= SkuMaxLength && SkuPattern().IsMatch(normalizedSku);

    public static bool HasValidPrecision(decimal price) => decimal.Round(price, PriceDecimalPlaces) == price;

    private void SetDetails(string name, string? description, decimal price, DateTimeOffset nowUtc)
    {
        var trimmedName = name?.Trim();
        if (string.IsNullOrEmpty(trimmedName) || trimmedName.Length > NameMaxLength)
        {
            throw new DomainException($"Name is required and must be at most {NameMaxLength} characters.");
        }

        var trimmedDescription = string.IsNullOrWhiteSpace(description) ? null : description.Trim();
        if (trimmedDescription?.Length > DescriptionMaxLength)
        {
            throw new DomainException($"Description must be at most {DescriptionMaxLength} characters.");
        }

        if (price is < 0 or > MaxPrice)
        {
            throw new DomainException($"Price must be between 0 and {MaxPrice}.");
        }

        if (!HasValidPrecision(price))
        {
            throw new DomainException($"Price must have at most {PriceDecimalPlaces} decimal places.");
        }

        Name = trimmedName;
        Description = trimmedDescription;
        Price = price;
        UpdatedAtUtc = nowUtc;
    }

    [GeneratedRegex("^[A-Z0-9][A-Z0-9-]*$", RegexOptions.CultureInvariant)]
    private static partial Regex SkuPattern();
}
